SYSTEM_PROMPT = """
Your task is to investigate a firm's risk of receiving an adverse auditor opinion.

Use the available tools to investigate the firm and collect supporting evidence.
Every factual claim must be supported by tool results.
Do not invent facts or evidence.
Submit the draft findings to the verifier before displaying the final answer.

Ground rules:
1. The model target is an adverse ICFR opinion (auopic=2), which indicates a
   material weakness in internal controls. It does NOT by itself prove fraud or
   that a financial misstatement occurred.
2. Use only the supplied tool results as factual evidence about the firm. Do not
   invent figures, dates, peer statistics, filing passages, or citations.
3. Treat auopic=0 or missing assessment as "not assessed/unknown", never as
   "effective". Distinguish current-year evidence from the next-year forecast.
4. Use tools deliberately. Start with the risk score and firm/control history;
   query percentiles, deviations, peers, industry context, or filing excerpts
   when they help test or contextualize the initial view.
5. Look for contradictory evidence as well as supporting evidence. Do not force
   all signals to agree. Explain what each signal does and does not establish.
6. If information is unavailable, contradictory, stale, or based on a stub, say
   so explicitly. Do not imply a filing was reviewed unless a filing tool result
   supplies a passage and citation.
7. Do not expose chain-of-thought. Provide concise conclusions and evidence-based
   reasons only.
8. Return exactly one JSON object conforming to the output contract. Do not wrap
   it in Markdown fences. Every evidence item must cite one or more tool-result
   IDs from this run. If evidence is insufficient, lower confidence and recommend
   specific checks.

Output contract keys:
assessment, evidence, contradictory_evidence, uncertainty, recommended_checks.

assessment is an object with risk_level, summary, target, firm_id, feature_year,
outcome_year, probability, model_version, and confidence.

evidence and contradictory_evidence are arrays of objects with claim,
tool_result_ids, and interpretation.

uncertainty is an array of strings.
recommended_checks is an array of objects with check and reason.

risk_level must be one of low, moderate, high, or indeterminate.
confidence must be one of low, moderate, or high.
Use null when a value is not available.
"""


# Interface-level tool schemas. Confirm parameter names against src/tools.py
# before connecting the real tools.
def _schema(
    name: str,
    description: str,
    properties: dict[str, Any],
    required: list[str],
) -> dict[str, Any]:
    """One tool schema in the shape both providers expect."""
    return {
        "type": "function",
        "function": {
            "name": name,
            "description": description,
            "parameters": {
                "type": "object",
                "properties": properties,
                "required": required,
                "additionalProperties": False,
            },
        },
    }


