class LLMClient(Protocol):
    def complete(
        self,
        messages: list[dict[str, Any]],
        tools: list[dict[str, Any]],
    ) -> dict[str, Any]:
        """Return a tool_call response or a final response."""
        ...


class AgentError(RuntimeError):
    pass


@dataclass
class AgentResult:
    output: dict[str, Any]
    trace: list[dict[str, Any]]
    status: str
    tool_calls_used: int
    run_id: str


def _jsonable(value: Any) -> Any:
    """Return a JSON-safe SNAPSHOT of value.

    The round trip is load-bearing. Returning the original object made the
    trace alias the live output, so verify_evidence_links, which removes
    items in place, silently rewrote the trace as well and destroyed the
    pre-verification output. Raw claim support then reads 100% by
    construction. See docs/EVALUATION_DESIGN.md section 6, item 2.
    """
    try:
        return json.loads(json.dumps(value))
    except (TypeError, ValueError):
        return str(value)


def _normalise_tool_result(
    value: Any,
    result_id: str,
) -> dict[str, Any]:
    if isinstance(value, Mapping):
        result = dict(value)
    else:
        result = {"data": value}

    result.setdefault("result_id", result_id)
    result.setdefault("source", None)
    return result


def validate_output(
    output: Any,
    firm_id: str,
    feature_year: int,
) -> dict[str, Any]:
    """Validate the required output shape."""

    required = {
        "assessment",
        "evidence",
        "contradictory_evidence",
        "uncertainty",
        "recommended_checks",
    }

    if isinstance(output, str):
        try:
            output = json.loads(output)
        except json.JSONDecodeError:
            output = None

    if not isinstance(output, dict) or not required.issubset(output):
        return {
            "assessment": {
                "risk_level": "indeterminate",
                "summary": (
                    "The agent did not return a valid assessment "
                    "matching the output contract."
                ),
                "target": (
                    "Adverse ICFR opinion (auopic=2) in the following "
                    "fiscal year; not a finding of fraud."
                ),
                "firm_id": str(firm_id),
                "feature_year": int(feature_year),
                "outcome_year": int(feature_year) + 1,
                "probability": None,
                "model_version": None,
                "confidence": "low",
            },
            "evidence": [],
            "contradictory_evidence": [],
            "uncertainty": [
                "The final response failed output-contract validation; "
                "review the trace and retry."
            ],
            "recommended_checks": [
                {
                    "check": "Review tool results and rerun the assessment.",
                    "reason": "A valid structured conclusion was not produced.",
                }
            ],
        }

    assessment = output.get("assessment")
    if not isinstance(assessment, dict):
        assessment = {}

    allowed_risk = {"low", "moderate", "high", "indeterminate"}
    allowed_confidence = {"low", "moderate", "high"}

    if assessment.get("risk_level") not in allowed_risk:
        assessment["risk_level"] = "indeterminate"

    if assessment.get("confidence") not in allowed_confidence:
        assessment["confidence"] = "low"

    assessment.setdefault("firm_id", str(firm_id))
    assessment.setdefault("feature_year", int(feature_year))
    assessment.setdefault("outcome_year", int(feature_year) + 1)
    assessment.setdefault("probability", None)
    assessment.setdefault("model_version", None)
    assessment.setdefault(
        "target",
        "Adverse ICFR opinion (auopic=2) in the following fiscal year; "
        "not a finding of fraud.",
    )
    assessment.setdefault("summary", "Assessment summary unavailable.")

    output["assessment"] = assessment

    for key in (
        "evidence",
        "contradictory_evidence",
        "uncertainty",
        "recommended_checks",
    ):
        if not isinstance(output.get(key), list):
            output[key] = []

    return output


def run_agent(
    *,
    firm_id: str,
    feature_year: int,
    user_question: str,
    llm: LLMClient,
    tools: Mapping[str, Callable[..., Any]],
    max_tool_calls: int = 8,
    tool_schemas: list[dict[str, Any]] | None = None,
) -> AgentResult:
    """Run the agent with a maximum number of executed tool calls."""

    if max_tool_calls < 0:
        raise ValueError("max_tool_calls must be >= 0")

    available = {
        name: fn for name, fn in tools.items()
        if name in TOOL_NAMES
    }

    if not available:
        raise ValueError("No recognised agent tools were provided.")

    run_id = datetime.now(timezone.utc).strftime(
        "%Y%m%dT%H%M%S%fZ"
    )

    schemas = (
        tool_schemas
        if tool_schemas is not None
        else [
            schema for schema in TOOL_SCHEMAS
            if schema["function"]["name"] in available
        ]
    )

    messages: list[dict[str, Any]] = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {
            "role": "user",
            "content": json.dumps(
                {
                    "firm_id": str(firm_id),
                    "feature_year": int(feature_year),
                    "outcome_year": int(feature_year) + 1,
                    "question": user_question,
                    "required_output_keys": [
                        "assessment",
                        "evidence",
                        "contradictory_evidence",
                        "uncertainty",
                        "recommended_checks",
                    ],
                }
            ),
        },
    ]

    trace: list[dict[str, Any]] = []
    calls = 0
    status = "completed"

    while True:
        response = llm.complete(messages, schemas)

        if not isinstance(response, dict):
            response = {"type": "final", "content": response}

        response_type = response.get("type")

        if response_type == "final":
            output = validate_output(
                response.get("content"),
                str(firm_id),
                int(feature_year),
            )
            trace.append(
                {
                    "event": "final_response",
                    "run_id": run_id,
                    "output": _jsonable(output),
                }
            )
            break

        if response_type != "tool_call":
            status = "invalid_llm_response"
            output = validate_output(
                None, str(firm_id), int(feature_year)
            )
            trace.append(
                {
                    "event": "invalid_llm_response",
                    "run_id": run_id,
                    "response": _jsonable(response),
                }
            )
            break

        name = response.get("name")
        arguments = response.get("arguments", {})

        if not isinstance(arguments, dict):
            trace.append(
                {
                    "event": "tool_rejected",
                    "tool": name,
                    "reason": "arguments_not_object",
                    "arguments": _jsonable(arguments),
                }
            )
            messages.append(
                {
                    "role": "assistant",
                    "content": (
                        "Tool call rejected: arguments must be a JSON "
                        "object. Return a valid final assessment or "
                        "a corrected tool call."
                    ),
                }
            )
            continue

        if name not in available:
            trace.append(
                {
                    "event": "tool_rejected",
                    "tool": name,
                    "reason": "unknown_or_unavailable_tool",
                    "arguments": _jsonable(arguments),
                }
            )
            messages.append(
                {
                    "role": "assistant",
                    "content": (
                        f"Tool call rejected: {name!r} is not available. "
                        "Use only available tool names."
                    ),
                }
            )
            continue

        if calls >= max_tool_calls:
            status = "call_budget_exhausted"
            trace.append(
                {
                    "event": "budget_exhausted",
                    "max_tool_calls": max_tool_calls,
                    "attempted_tool": name,
                    "arguments": _jsonable(arguments),
                }
            )
            messages.append(
                {
                    "role": "assistant",
                    "content": (
                        f"Tool-call budget of {max_tool_calls} has been "
                        "exhausted. Do not call any more tools. Return "
                        "the best supported assessment now, clearly "
                        "stating any evidence gaps."
                    ),
                }
            )

            response = llm.complete(messages, [])
            output = validate_output(
                response.get("content")
                if isinstance(response, dict)
                and response.get("type") == "final"
                else None,
                str(firm_id),
                int(feature_year),
            )
            trace.append(
                {
                    "event": "final_response_after_budget",
                    "run_id": run_id,
                    "output": _jsonable(output),
                }
            )
            break

        call_id = f"tool_{calls + 1}"
        started = datetime.now(timezone.utc).isoformat()

        event: dict[str, Any] = {
            "event": "tool_call",
            "call_id": call_id,
            "tool": name,
            "arguments": _jsonable(arguments),
            "started_at": started,
        }

        try:
            value = available[name](**arguments)
            result = _normalise_tool_result(
                value, f"result_{calls + 1}"
            )
            event.update(
                {"status": "ok", "result": _jsonable(result)}
            )
            messages.append(
                {
                    "role": "assistant",
                    "content": json.dumps(
                        {"tool_call": name, "arguments": arguments}
                    ),
                }
            )
            messages.append(
                {
                    "role": "tool",
                    "name": name,
                    "content": json.dumps(result, default=str),
                }
            )

        except Exception as exc:
            result = {
                "result_id": f"result_{calls + 1}",
                "error": type(exc).__name__,
                "message": str(exc),
                "source": None,
            }
            event.update({"status": "error", "error": result})
            messages.append(
                {
                    "role": "assistant",
                    "content": json.dumps(
                        {"tool_call": name, "arguments": arguments}
                    ),
                }
            )
            messages.append(
                {
                    "role": "tool",
                    "name": name,
                    "content": json.dumps(result),
                }
            )

        event["finished_at"] = datetime.now(timezone.utc).isoformat()
        trace.append(event)
        calls += 1

    return AgentResult(
        output=output,
        trace=trace,
        status=status,
        tool_calls_used=calls,
        run_id=run_id,
    )


def verify_evidence_links(
    output: dict[str, Any],
    trace: list[dict[str, Any]],
) -> dict[str, Any]:
    """Check that cited evidence IDs exist in successful tool results."""

    known_ids = {
        event.get("result", {}).get("result_id")
        for event in trace
        if event.get("event") == "tool_call"
        and event.get("status") == "ok"
    }

    report = {
        "verified_items": 0,
        "blocked_items": 0,
        "issues": [],
    }

    for section in ("evidence", "contradictory_evidence"):
        kept = []

        for item in output.get(section, []):
            refs = (
                item.get("tool_result_ids", [])
                if isinstance(item, dict)
                else []
            )

            if refs and all(ref in known_ids for ref in refs):
                kept.append(item)
                report["verified_items"] += 1
            else:
                report["blocked_items"] += 1
                report["issues"].append(
                    {
                        "section": section,
                        "item": item,
                        "reason": "Missing or unknown tool_result_ids",
                    }
                )

        output[section] = kept

    return report